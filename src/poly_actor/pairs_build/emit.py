"""Assemble the four pairs and write config/pairs.yaml."""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

from poly_actor.pairs_build.btc import build_btc
from poly_actor.pairs_build.calendars import run_time_cross_checks
from poly_actor.pairs_build.consts import GLOBAL_CONVENTIONS, TODAY
from poly_actor.pairs_build.cpi import build_cpi
from poly_actor.pairs_build.fed import build_fed
from poly_actor.pairs_build.gamma import GammaClient
from poly_actor.pairs_build.recession import build_recession

HEADER = (
    "# config/pairs.yaml -- market<->ticker pair definitions for milestone 1.\n"
    "# GENERATED by scripts/build_pairs.py from data/scratch/step2/*.json. Do not hand-edit;\n"
    "# edit the script and re-run (add --refetch to refresh the Gamma dumps).\n"
    "# Rationale, rejected candidates, open risks: docs/step2_pairs.md.\n"
)
APPROVED_STATUS = "status: approved  # user approved all 4 pairs 2026-10-01 after validation\n"


def build_pairs_yaml(gamma: GammaClient, out_path: Path) -> None:
    run_time_cross_checks(gamma)
    doc = {
        "status": "draft",
        "generated": TODAY,
        "generated_by": "scripts/build_pairs.py (step 2, round 3)",
        "evidence_dir": "data/scratch/step2/",
        "preregistration": "docs/preregistration.md",
        "conventions": GLOBAL_CONVENTIONS,
        "pairs": [build_fed(gamma), build_recession(gamma), build_btc(gamma), build_cpi(gamma)],
    }
    text = yaml.dump(doc, Dumper=yaml.SafeDumper, sort_keys=False, allow_unicode=True, width=110)
    text = text.replace("status: draft\n", APPROVED_STATUS, 1)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(HEADER + text, encoding="utf-8")
    print(f"wrote {out_path} ({len(text)} chars)", file=sys.stderr)
